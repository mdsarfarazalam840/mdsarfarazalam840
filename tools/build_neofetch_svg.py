def escape(text):
    return text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')


def leader(reserve, value_length):
    """A dot leader sized so leader + value is always `reserve` + 2 characters.

    neofetch_stats.justify_format() rebuilds leaders with this exact rule when it
    writes new numbers in, which is what keeps the card's right edge flush as the
    values grow.
    """
    return ' ' + ('.' * max(0, reserve - value_length)) + ' '


def pairs(tokens):
    """Index the val tokens whose width is absorbed by the leader before them."""
    absorbed = set()
    for index, token in enumerate(tokens[:-1]):
        following = tokens[index + 1]
        if token[0] == 'dots' and token[1] and following[0] == 'val':
            absorbed.add(index + 1)
    return absorbed


def measure(tokens):
    """Character width of a line, treating 'auto' leaders as zero.

    A leader with an id plus the value after it always occupies reserve + 2
    characters, so the value itself is not counted separately.
    """
    absorbed = pairs(tokens)
    total = 0
    for index, token in enumerate(tokens):
        if token[0] in ('key', 'lit'):
            total += len(token[1])
        elif token[0] == 'val':
            if index not in absorbed:
                total += len(token[1])
        elif token[0] == 'dots':
            reserve = token[2]
            if reserve != 'auto':
                total += reserve + 2
    return total


def resolve(tokens):
    """Turn one line's tokens into (rendered tokens, {id: reserved width})."""
    autos = [t for t in tokens if t[0] == 'dots' and t[2] == 'auto']
    if len(autos) > 1:
        raise ValueError("a line may contain at most one 'auto' dot leader")
    slack = LINE_WIDTH - measure(tokens)
    reserves, out = {}, []
    for token in tokens:
        if token[0] == 'dots':
            ident, reserve = token[1], token[2]
            if reserve == 'auto':
                # The value sitting after this leader is already counted in
                # measure(), so the leader gets all remaining slack.
                reserve = slack - 2
                if reserve < 0:
                    raise ValueError(f'line is {-slack} chars too long: {tokens}')
            out.append(('dots', ident, reserve))
            if ident:
                reserves[ident] = reserve
        else:
            out.append(token)
    return out, reserves


def render_line(tokens, y, theme):
    """Render one info line as SVG tspans, plus its reserved-width map."""
    if tokens and tokens[0][0] == 'header':
        title = tokens[0][1]
        # First header doubles as the prompt line, the rest get a leading dash.
        label = title if y == FIRST_LINE_Y else f'- {title} '
        rule = '-' + '—' * max(0, LINE_WIDTH - len(label) - 4) + '-—-'
        return (f'<tspan x="{INFO_X}" y="{y}">{escape(label)}</tspan>{escape(rule)}', {})

    resolved, reserves = resolve(tokens)
    absorbed = pairs(resolved)
    pieces, first, pending = [], True, None
    for index, token in enumerate(resolved):
        if token[0] == 'dots':
            ident, reserve = token[1], token[2]
            ident_attr = f' id="{ident}"' if ident else ''
            # The leader's width depends on the value that follows it, so hold
            # it back until that value is known.
            pending = (ident_attr, reserve, len(pieces))
            pieces.append(None)
            continue
        if token[0] == 'key':
            pieces.append(f'<tspan class="key">{escape(token[1])}</tspan>')
            continue
        if token[0] == 'val':
            text, ident, cls = token[1], token[2], token[3]
            ident_attr = f' id="{ident}"' if ident else ''
            if pending and index in absorbed:
                dots_attr, reserve, slot = pending
                pieces[slot] = f'<tspan class="cc"{dots_attr}>{escape(leader(reserve, len(text)))}</tspan>'
                pending = None
            pieces.append(f'<tspan class="{cls}"{ident_attr}>{escape(text)}</tspan>')
            continue
        text = token[1]
        if first:
            # Anchor the line's x/y on its very first tspan.
            pieces.append(f'<tspan x="{INFO_X}" y="{y}" class="cc">{escape(text)}</tspan>')
        else:
            pieces.append(escape(text))
        first = False
    # Any leader with no value after it just fills its reserved width.
    if pending:
        dots_attr, reserve, slot = pending
        pieces[slot] = f'<tspan class="cc"{dots_attr}>{escape(leader(reserve, 0))}</tspan>'
    if first:
        pieces.insert(0, f'<tspan x="{INFO_X}" y="{y}"></tspan>')
    return (''.join(piece for piece in pieces if piece is not None), reserves)


def load_art():
    """The shaded mosaic from tools/image_to_ascii.py --shaded, if it exists."""
    if not os.path.exists(ART_FILE):
        return None
    with open(ART_FILE, encoding='utf-8') as handle:
        return json.load(handle)


def mix(start, end, amount):
    """Blend two #rrggbb colours, `amount` of the way from start to end."""
    channels = []
    for offset in (1, 3, 5):
        low = int(start[offset:offset + 2], 16)
        high = int(end[offset:offset + 2], 16)
        channels.append(round(low + (high - low) * amount))
    return '#%02x%02x%02x' % tuple(channels)


def art_styles(art, theme):
    """One CSS class per brightness level, panel colour up to full ink."""
    levels = art['levels']
    rules = []
    for level in range(1, levels):
        colour = mix(theme['art_panel'], theme['art_ink'], level / (levels - 1))
        rules.append(f'.m{level:x} {{fill: {colour};}}')
    return '\n'.join(rules)


def art_runs(row):
    """Split a row of hex levels into (level, start column, length) runs."""
    runs, start = [], 0
    while start < len(row):
        end = start
        while end < len(row) and row[end] == row[start]:
            end += 1
        level = int(row[start], 16)
        if level:
            runs.append((level, start, end - start))
        start = end
    return runs


def render_art(art, theme):
    """The mosaic as one tspan per run of equally bright cells.

    Every run is placed at an absolute x and pinned to an exact pixel width with
    textLength, so the grid keeps its geometry whatever monospace font the
    renderer ends up using -- the block characters are squeezed or stretched to
    the mosaic's pitch rather than following the font's own advance width.
    """
    columns, rows = art['columns'], art['rows']
    pitch_x = ART_WIDTH / columns
    pitch_y = ART_HEIGHT / rows
    font_size = pitch_y / ART_BLOCK_RISE
    tspans = []
    for index, row in enumerate(art['grid']):
        baseline = ART_TOP_Y + (index + 1) * pitch_y
        for level, start, length in art_runs(row):
            tspans.append(
                f'<tspan class="m{level:x}" x="{ART_X + start * pitch_x:.2f}"'
                f' y="{baseline:.2f}" textLength="{length * pitch_x:.2f}"'
                f' lengthAdjust="spacingAndGlyphs">{"█" * length}</tspan>')
    panel = (f'<rect x="{ART_X - ART_PADDING}" y="{ART_TOP_Y - ART_PADDING}"'
             f' width="{ART_WIDTH + 2 * ART_PADDING}"'
             f' height="{ART_HEIGHT + 2 * ART_PADDING}" rx="10"'
             f' fill="{theme["art_panel"]}"/>')
    body = (f'{panel}\n<g clip-path="url(#artClip)">\n'
            f'<text x="{ART_X}" y="{ART_TOP_Y}" font-size="{font_size:.3f}px">\n'
            + '\n'.join(tspans) + '\n</text>\n</g>')
    clip = (f'<clipPath id="artClip"><rect x="{ART_X}" y="{ART_TOP_Y}"'
            f' width="{ART_WIDTH}" height="{ART_HEIGHT}"/></clipPath>')
    return clip, body, len(tspans)


def render_ascii(theme):
    """The plain ASCII_ART block, one tspan per line."""
    art_start_y = FIRST_LINE_Y + LINE_HEIGHT  # nudge the art down one row
    tspans = '\n'.join(
        f'<tspan x="{ART_X}" y="{art_start_y + index * LINE_HEIGHT}">{escape(line)}</tspan>'
        for index, line in enumerate(ASCII_ART.strip('\n').split('\n')))
    return '', f'<text x="{ART_X}" y="{FIRST_LINE_Y}" fill="{theme["fg"]}" class="ascii">\n{tspans}\n</text>'


def build(filename, theme):
    art = load_art()
    if art:
        clip, art_markup, _ = render_art(art, theme)
        art_css = '\n' + art_styles(art, theme)
    else:
        clip, art_markup = render_ascii(theme)
        art_css = ''

    info_tspans, reserves = [], {}
    for index, tokens in enumerate(LINES):
        rendered, line_reserves = render_line(tokens, FIRST_LINE_Y + index * LINE_HEIGHT, theme)
        info_tspans.append(rendered)
        reserves.update(line_reserves)

    defs = f'<defs>{clip}</defs>\n' if clip else ''
    svg = f"""<?xml version='1.0' encoding='UTF-8'?>
<svg xmlns="http://www.w3.org/2000/svg" font-family="ConsolasFallback,Consolas,monospace" width="{CANVAS_WIDTH}px" height="{CANVAS_HEIGHT}px" font-size="16px">
<style>
@font-face {{
src: local('Consolas'), local('Consolas Bold');
font-family: 'ConsolasFallback';
font-display: swap;
-webkit-size-adjust: 109%;
size-adjust: 109%;
}}
.key {{fill: {theme['key']};}}
.value {{fill: {theme['value']};}}
.addColor {{fill: {theme['add']};}}
.delColor {{fill: {theme['del']};}}
.cc {{fill: {theme['cc']};}}
text, tspan {{white-space: pre;}}{art_css}
</style>
{defs}<rect width="{CANVAS_WIDTH}px" height="{CANVAS_HEIGHT}px" fill="{theme['bg']}" rx="15"/>
{art_markup}
<text x="{INFO_X}" y="{FIRST_LINE_Y}" fill="{theme['fg']}">
{chr(10).join(info_tspans)}
</text>
</svg>"""

    with open(filename, 'w', encoding='utf-8', newline='\n') as handle:
        handle.write(svg)
    return reserves


