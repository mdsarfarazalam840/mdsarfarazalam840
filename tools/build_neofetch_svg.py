# --- token helpers -------------------------------------------------------
# A line is a list of tokens. Tokens render in order:
#   key(text)          an orange field name
#   lit(text)          plain punctuation / separators
#   val(text, id)      a value, optionally addressable by neofetch_stats.py
#   dots(id, reserve)  a dot leader. reserve is the number of characters kept
#                      free for the value that follows it; 'auto' stretches the
#                      leader so the whole line lands on LINE_WIDTH.


def key(text):
    return ('key', text)


def lit(text):
    return ('lit', text)


def val(text, ident=None, cls='value'):
    return ('val', text, ident, cls)


def dots(ident=None, reserve='auto'):
    return ('dots', ident, reserve)


def field(name, value, ident=None, reserve='auto'):
    """A whole `. Name: ..... value` line, the common case."""
    tokens = [lit('. ')]
    parts = name.split('.')
    for index, part in enumerate(parts):
        if index:
            tokens.append(key('.'))
        tokens.append(key(part))
    tokens += [lit(':'), dots(f'{ident}_dots' if ident else None, reserve),
               val(value, ident)]
    return tokens


def header(title):
    return [('header', title)]


