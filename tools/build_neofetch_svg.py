"""Regenerate the neofetch-style profile cards (dark_mode.svg and light_mode.svg).

Everything about the card's *layout and static content* lives in this file. Run it
whenever you want to change a line, reorder sections, or swap the art:

    python tools/build_neofetch_svg.py

The left column is either plain ASCII (the ASCII_ART constant below) or, when
cache/ascii_art.json exists, a shaded mosaic generated by tools/image_to_ascii.py
--shaded. Delete that file to fall back to the ASCII sigil.

The live numbers (repos, stars, commits, followers, lines of code, uptime) are
filled in later by neofetch_stats.py, which runs in CI. This script only writes
the placeholder values and, crucially, the dot-leader padding those values are
justified against. The widths it reserves are written to cache/svg_layout.json so
neofetch_stats.py stays in sync automatically -- do not hand-edit that file.

Adapted from the profile card idea in github.com/Andrew6rant/Andrew6rant.
"""

